#!/usr/bin/env bash
# Phase 99: bundle artifacts into a single tarball + emit a summary.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../tools/lib.sh
source "${SCRIPT_DIR}/../tools/lib.sh"

PHASE=99_collect_artifacts
init_phase "${PHASE}"

ARCH="$(target_arch)"
tarball="${ARTIFACT_DIR}/sunbeam-${ARCH}-${RUN_ID}.tar.zst"
tmp_tarball="${ARTIFACT_DIR}.sunbeam-${ARCH}-${RUN_ID}.tar.zst.tmp"
share_tarball="${ARTIFACT_DIR}/test-share-${ARCH}-${RUN_ID}.tar.zst"
share_tmp="${ARTIFACT_DIR}.test-share-${ARCH}-${RUN_ID}.tar.zst.tmp"
local_artifacts_dir="${ARTIFACT_DIR}/local-artifacts"
local_tarball="${ARTIFACT_DIR}/local-artifacts-${ARCH}-${RUN_ID}.tar.zst"
local_tmp="${ARTIFACT_DIR}.local-artifacts-${ARCH}-${RUN_ID}.tar.zst.tmp"

export_local_artifacts() {
    local dest="$1"
    local found=0
    local kind src ext f

    rm -rf "${dest}"
    mkdir -p "${dest}/charms" "${dest}/snaps" "${dest}/rocks"

    for kind in charms snaps rocks; do
        src="${REPO_ROOT}/${kind}"
        [[ -d "${src}" ]] || continue
        case "${kind}" in
            charms) ext=charm ;;
            snaps)  ext=snap ;;
            rocks)  ext=rock ;;
        esac
        while IFS= read -r -d '' f; do
            cp -a "${f}" "${dest}/${kind}/"
            found=1
        done < <(find "${src}" -maxdepth 1 -type f -name "*.${ext}" -print0 2>/dev/null)
    done

    if (( found == 0 )); then
        rm -rf "${dest}"
        log "no local charms/snaps/rocks found; skipping local-artifacts export"
        return 1
    fi

    rmdir "${dest}/charms" "${dest}/snaps" "${dest}/rocks" 2>/dev/null || true
    if [[ -f "${ARTIFACT_DIR}/source_provenance.txt" ]]; then
        cp -a "${ARTIFACT_DIR}/source_provenance.txt" "${dest}/"
    fi

    cat > "${dest}/README.md" <<EOF
# Local s390x artifacts

Generated by phase 99 for run ${RUN_ID}.

Verify:

    sha256sum -c SHA256SUMS

## Charms

    juju deploy ./charms/<name>_s390x.charm <application>

Or reference the local path from a bundle:

    charm: ./charms/<name>_s390x.charm

## Snaps

    sudo snap install --dangerous --devmode ./snaps/<name>_s390x.snap

Use --dangerous without --devmode for a strict local snap.

## Rocks

    sudo /snap/k8s/current/bin/ctr \
      --address /run/containerd/containerd.sock \
      --namespace k8s.io images import ./rocks/<name>_s390x.rock

Or use the Canonical Kubernetes CLI:

    sudo k8s images import --base-name <repository> ./rocks/<name>_s390x.rock
EOF

    (
        cd "${dest}"
        find . -type f ! -name SHA256SUMS -print0             | sort -z | xargs -0 -r sha256sum > SHA256SUMS
    )
    return 0
}

log_step "building compact test-share report"
"${SCRIPT_DIR}/../tools/build_test_share_report.sh"

if export_local_artifacts "${local_artifacts_dir}"; then
    log_step "creating ${local_tarball}"
    tar --zstd -cf "${local_tmp}" -C "${ARTIFACT_DIR}" local-artifacts
    mv "${local_tmp}" "${local_tarball}"
    sha256sum "${local_tarball}" > "${local_tarball}.sha256"
else
    local_tarball=""
fi

log_step "creating ${tarball}"

# Write outside ARTIFACT_DIR first so tar never archives the file it is creating.
tar --zstd \
    --exclude="$(basename "${tarball}")" \
    --exclude="$(basename "${local_tarball:-local-artifacts-none}")" \
    -cf "${tmp_tarball}" \
    -C "${ARTIFACT_DIR}" .
mv "${tmp_tarball}" "${tarball}"
sha256sum "${tarball}" > "${tarball}.sha256"

log_step "creating ${share_tarball}"
tar --zstd -cf "${share_tmp}" -C "${ARTIFACT_DIR}" test-share
mv "${share_tmp}" "${share_tarball}"
sha256sum "${share_tarball}" > "${share_tarball}.sha256"

log_step "phase status summary:"
{
    printf '\n%-25s %-10s\n' PHASE STATUS
    printf '%-25s %-10s\n' ----- ------
    for p in 00_check_host 01_install_prereqs 02_prepare_node \
             03_setup_s390x_cni 04_bootstrap 05_deploy_machine_plane \
             06_configure 07_smoke_cloud 08_capture_state \
             09_validate_tempest; do
        if [[ -f "${PHASE_STATUS_DIR}/${p}.failed" ]]; then
            st="FAILED(rc=$(cat "${PHASE_STATUS_DIR}/${p}.failed"))"
        elif [[ -f "${PHASE_STATUS_DIR}/${p}.done" ]]; then
            st=DONE
        else
            st=SKIPPED
        fi
        printf '%-25s %-10s\n' "${p}" "${st}"
    done
    printf '\nfull diagnostic bundle: %s\n' "${tarball}"
    printf 'publishable test-share bundle: %s\n' "${share_tarball}"
    if [[ -n "${local_tarball}" ]]; then
        printf 'local artifacts bundle: %s\n' "${local_tarball}"
    fi
} | tee -a "${PHASE_LOG}"

phase_done "${PHASE}"
